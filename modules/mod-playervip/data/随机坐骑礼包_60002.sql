-- 1. 创建坐骑法术表（存礼包可开出的坐骑法术 ID、坐骑名称及开出权重）
--    chance 为开出权重（相对值）：值越大越容易开出；默认 100，不写 chance 即用默认值。
--    最终概率 = 该坐骑 chance / 所有「未学习坐骑」chance 之和
CREATE TABLE IF NOT EXISTS `custom_mount_gift_spells` (
  `entry` int unsigned NOT NULL COMMENT '礼包物品ID（item_template.entry）',
  `spellId` int unsigned NOT NULL COMMENT '坐骑法术ID（坐骑物品的 spellid_2）',
  `name` varchar(255) NOT NULL DEFAULT '' COMMENT '坐骑名称（说明/备注）',
  `chance` int unsigned NOT NULL DEFAULT 100 COMMENT '开出权重（相对值，越大越容易开出；0 表示永不随机到）',
  PRIMARY KEY (`entry`,`spellId`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='随机坐骑礼包：礼包可开出的坐骑法术ID、名称及权重';

