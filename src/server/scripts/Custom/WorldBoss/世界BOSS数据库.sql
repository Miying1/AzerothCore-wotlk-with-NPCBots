-- ---------------------------------------------------------------------
-- 【脱战机制说明】
-- 本体（120100~120111）**保留** type_flags 的 CREATURE_TYPE_FLAG_BOSS_MOB (0x4) 位：
--   它决定核心 isWorldBoss() 为真，从而提供“??”等级显示与免疫击退，是刻意的表现设计。
-- 但该位同时会让核心 Creature::CanCreatureAttack 取消「近期受伤即可离开刷新点」的豁免，
--   于是回家距离判定（CreatureLeashRadius，默认 30 码）恒定生效 —— 一旦被拉开 30 码，
--   全部仇恨引用会同时被置为 OFFLINE，SelectVictim 随即以 EVADE_REASON_OTHER 兜底脱战，
--   配合 flags_extra 的 CREATURE_FLAG_EXTRA_HARD_RESET，表现就是“打着打着BOSS脱战并消失”。
-- 处理方式（代码侧，无需改数据）：WorldBossGuardAI::CheckLeash() 在锁定期间做两件事：
--   ① 把 IDLE 运动生成器换成默认 idle —— Creature::CanCreatureAttack 的距离基准优先取 IDLE 槽的
--      GetResetPosition()，本体 MovementType=1（随机漫游）时它返回“漫游目标点/初始点”而非
--      m_homePosition，必须先让它返回 false；
--   ② 让 m_homePosition 跟随 BOSS 当前位置（进入战斗时保存真实出生点，脱战/退场前还原），
--      使 30 码判定恒为真。这样本框架的 WORLD_BOSS_LEASH_RANGE（150 码）成为唯一脱战距离。
--   附注：副本地图（GetMap()->IsDungeon()）内核心会提前 return true，完全不做该距离判定，
--      因此副本BOSS不受此问题影响，本机制只在开放世界地图上有意义。
-- 若曾按上一版说明执行过下面这条（去掉 BOSS_MOB），请用紧随其后的语句还原：
--   UPDATE `creature_template` SET `type_flags` = `type_flags` & ~0x4,
--       `flags_extra` = `flags_extra` | 0x40000000
--   WHERE `entry` IN (120100,120101,120102,120103,120104,120105,120106,120107,120108,120109,120110,120111);
