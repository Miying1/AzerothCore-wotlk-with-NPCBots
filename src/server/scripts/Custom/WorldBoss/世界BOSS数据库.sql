--   但 ObjectMgr 启动校验会检查它，于是每个刷新点都会刷出下面这条 LOG_ERROR：
--     Table `creature` have creature (SpawnId: ? Entry: ?) with `creature_template`.`flags_extra`
--     including CREATURE_FLAG_EXTRA_INSTANCE_BIND but creature are not in instance.
--   现在本体取值为 2147483656 (0x80000008 = HARD_RESET|NO_PARRY_HASTEN) 与 544 (0x220)。
--   存量数据库无需重导，执行下面这条即可（幂等）：
--     UPDATE `creature_template` SET `flags_extra` = `flags_extra` & ~0x1
